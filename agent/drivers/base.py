"""The four driver interfaces. The core pipeline only talks to these, so a new
forge, package ecosystem or platform is one new class, not a change to the core.

  Source     where a service's code lives and how a change is proposed
  Ecosystem  how a package manager pins, fetches and ships a dependency
  Target     where workloads run: discovery, canary, promote, rollback, mitigation
  Probe      safe exploit check, defined in agent/probes.py

Methods are only the ones the pipeline calls.
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from typing import Optional, Protocol

from ..schemas import Component, Workload


class Source(Protocol):
    name: str
    url: str
    path: Path

    def head(self) -> str: ...
    def start_change(self, branch: str) -> None: ...
    def commit(self, message: str) -> str: ...
    def accept_change(self, branch: str) -> None: ...
    def abandon_change(self, branch: str) -> None: ...
    def config(self) -> dict: ...


@dataclass
class Sensitive:
    label: str
    regex: str
    severity: str          # soft | info
    kind: str = ""         # env | network | exec | load: used for the exfiltration rule


class Ecosystem(Protocol):
    name: str              # maven | pypi
    language: str
    sensitive: list[Sensitive]

    def detect(self, repo: Path) -> bool: ...
    def components(self, repo: Path) -> list[Component]: ...
    def artifacts(self, name: str, version: str) -> tuple[Path, Path]: ...
    def sources(self, source_artifact: Path) -> dict[str, list[str]]: ...
    def shipped_without_source(self, shipped: Path, sources: dict[str, list[str]]) -> list[str]: ...
    def load_time_lines(self, path: str, added: list[str], new_lines: list[str]) -> list[str]: ...
    def new_dependencies(self, old_shipped: Path, new_shipped: Path) -> list[str]: ...
    def bump(self, repo: Path, comp: Component, version: str) -> list[str]: ...
    def grep_terms(self, comp: Component) -> list[str]: ...


@dataclass
class HttpResult:
    status: int
    body: str


class Target(Protocol):
    name: str
    kind: str

    def list_workloads(self) -> list[Workload]: ...
    def http(self, wl: Workload, path: str, headers: Optional[dict] = None,
             via: str = "public", timeout: float = 8) -> HttpResult: ...
    def callback_hits(self, wl: Workload, since: float) -> list[dict]: ...
    def gateway_config(self, wl: Workload) -> Optional[str]: ...
    def deploy_canary(self, wl: Workload, image: str) -> None: ...
    def remove_canary(self, wl: Workload) -> None: ...
    def promote(self, wl: Workload, image: str) -> str: ...
    def rollback(self, wl: Workload, previous_image: str) -> None: ...
    def apply_mitigation(self, wl: Workload, key: str, rule: str) -> None: ...
    def clear_mitigations(self, wl: Workload) -> None: ...


class DriverError(RuntimeError):
    pass
